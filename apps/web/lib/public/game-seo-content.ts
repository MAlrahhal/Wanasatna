export function getGameSeoPage(gameId: string): GameSeoPage | null {
  if (!isPlayableGameId(gameId)) {
    return null;
  }

  return pages[gameId];
}

export function listGameSeoPages(): GameSeoPage[] {
  return PLAYABLE_GAME_IDS.map((gameId) => pages[gameId]);
}

export function buildGamePageJsonLd(page: GameSeoPage) {
  const url = `${SITE_ORIGIN}${getGameInformationPath(page.id)}`;

  return [
    {
      '@context': 'https://schema.org',
      '@type': 'WebPage',
      name: page.title,
      description: page.metaDescription,
      url,
      inLanguage: 'ar',
      isPartOf: {
        '@type': 'WebSite',
        name: BRAND_NAME_AR,
        url: `${SITE_ORIGIN}/`,
      },
    },
    {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        {
          '@type': 'ListItem',
          position: 1,
          name: 'الرئيسية',
          item: `${SITE_ORIGIN}/`,
        },
        {
          '@type': 'ListItem',
          position: 2,
          name: 'الألعاب',
          item: `${SITE_ORIGIN}${PUBLIC_ROUTES.games}`,
        },
        {
          '@type': 'ListItem',
          position: 3,
          name: page.title,
          item: url,
        },
      ],
    },
  ];
}
